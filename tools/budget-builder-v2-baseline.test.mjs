import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {approvedBaseline} from '../docs/portfolio-operations-dashboard/features/budget-v2/store.mjs';
import {fiscalPeriods} from '../docs/portfolio-operations-dashboard/features/budget-v2/engine.mjs';
const communityId=randomUUID();
const row=(year,months,changes={})=>({version_id:randomUUID(),community_id:communityId,calendar_year:year,status:'locked',covered_months:months,payload:{rows:[]},...changes});
const full=Array.from({length:12},(_,i)=>i);
const first=row(2027,[7,8,9,10,11]),second=row(2028,[0,1,2,3,4,5,6]),adjacent=row(2027,[0,1,2,3,4,5,6]);
const periods=fiscalPeriods(2028,8),requests=[];
const central={fetchJson:async url=>{requests.push(new URL(url,'https://atlas.example'));return [second,adjacent,first];}};
assert.deepEqual((await approvedBaseline(central,communityId,periods)).map(r=>r.version_id),[first.version_id,second.version_id]);
assert.equal(requests[0].searchParams.get('calendar_year'),'in.(2027,2028)');
assert.equal(requests[0].searchParams.get('community_id'),`eq.${communityId}`);
assert.equal(requests[0].searchParams.get('status'),'eq.locked');
assert(requests[0].searchParams.get('select').includes('covered_months'));
const annual=row(2029,full);
assert.deepEqual(await approvedBaseline({fetchJson:async()=>[annual]},communityId,fiscalPeriods(2029,1)),[annual]);
await assert.rejects(()=>approvedBaseline({fetchJson:async()=>[first]},communityId,periods),/missing for 2028-01/);
await assert.rejects(()=>approvedBaseline({fetchJson:async()=>[first,second,row(2028,[0])]},communityId,periods),/ambiguous for 2028-01/);
await assert.rejects(()=>approvedBaseline({fetchJson:async()=>[first,{...second,community_id:randomUUID()}]},communityId,periods),/could not be verified/);
await assert.rejects(()=>approvedBaseline({fetchJson:async()=>[first,{...second,status:'draft'}]},communityId,periods),/could not be verified/);
await assert.rejects(()=>approvedBaseline({fetchJson:async()=>{throw Error('Read unavailable');}},communityId,periods),/Read unavailable/);
await assert.rejects(()=>approvedBaseline({fetchJson:async()=>{assert.fail('invalid scope must not be read');}},communityId,['2028-13']),/fiscal periods/);
console.log('PASS Budget Builder baseline: all fiscal-year segments, exact community/status/month coverage, adjacent segment exclusion, missing/ambiguous/read failures remain blocked');
